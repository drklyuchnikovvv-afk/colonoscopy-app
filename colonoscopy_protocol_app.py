import streamlit as st

st.set_page_config(
    page_title="Универсальный протоколизатор колоноскопии",
    page_icon="🏥",
    layout="wide"
)

st.title("🏥 Универсальный протоколизатор колоноскопии")
st.markdown("""
Автоматизированный генератор протоколов эндоскопического исследования с учетом стандартов описания отделов, 
Бостонской шкалы подготовки (BBPS), классификации Язвенного Колита (Монреаль, Mayo, UCEIS) и полипов (Парижская шкала, NICE).
""")

st.divider()

# Создаем колонки для удобного ввода
col_left, col_right = st.columns([1, 1], gap="large")

with col_left:
    # ---------------------------------------------------------
    # 1. Границы осмотра и анатомические структуры
    # ---------------------------------------------------------
    st.header("1. Общие сведения и глубина осмотра")
    
    depth = st.selectbox(
        "Аппарат введен",
        [
            "тотальная колоноскопия + илеоскопия (на 15-20 см)",
            "тотальная колоноскопия (до купола слепой кишки)",
            "сигмоидоскопия / осмотр левых отделов",
            "неполный осмотр (до средне-ампулярного отдела / сигмовидной кишки)"
        ]
    )

    st.subheader("Терминальный отдел подвздошной кишки (TI)")
    ti_status = st.selectbox(
        "Состояние слизистой TI",
        [
            "не осмотрен",
            "норма (просвет не изменен, ворсинчатый рельеф сохранен, слизистая розовая, эрозий и язв нет)",
            "картина ретроградного «бэквош»-илеита (диффузная эритема, мелкие эрозии на фоне панколита)",
            "афтоидные язвы / язвы-трещины (дифференциальный диагноз с болезнью Крона)"
        ]
    )

    st.subheader("Илеоцекальный клапан (Баугиниева заслонка)")
    ic_form = st.selectbox("Форма клапана", ["плоская", "уплощенная", "полиповидная", "цилиндрическая", "грибовидная"])
    ic_orient = st.selectbox("Ориентация клапана", ["в купол слепой кишки", "перпендикулярно длиннику восходящей кишки", "в восходящую кишку"])
    ic_ostium = st.selectbox("Состояние устья", ["сомкнуто", "полуоткрыто", "зияет"])
    ic_ostium_shape = st.selectbox("Форма устья", ["губовидное", "щелевидное", "округлое"])

    # ---------------------------------------------------------
    # 2. Подготовка по Бостонской шкале (BBPS)
    # ---------------------------------------------------------
    st.header("2. Оценка подготовки (Бостонская шкала / BBPS)")
    
    b_col1, b_col2, b_col3 = st.columns(3)
    with b_col1:
        bbps_r = st.slider("Правый отдел (0-3)", 0, 3, 3, help="Слепая и восходящая кишка")
    with b_col2:
        bbps_t = st.slider("Поперечный отдел (0-3)", 0, 3, 3, help="Поперечно-ободочная кишка и изгибы")
    with b_col3:
        bbps_l = st.slider("Левый отдел (0-3)", 0, 3, 3, help="Нисходящая, сигмовидная и прямая кишка")

    bbps_total = bbps_r + bbps_t + bbps_l
    is_adequate = (bbps_total >= 6) and (min(bbps_r, bbps_t, bbps_l) >= 2)
    prep_status_str = "Адекватная" if is_adequate else "Неадекватная (требуется повторный осмотр / сокращение интервала)"
    
    st.info(f"**Итоговый балл BBPS:** {bbps_r} + {bbps_t} + {bbps_l} = **{bbps_total} / 9** ({prep_status_str})")

    # ---------------------------------------------------------
    # 3. Общее описание ободочной и прямой кишки
    # ---------------------------------------------------------
    st.header("3. Базовые характеристики слизистой толстой кишки")
    
    colon_lumen = st.selectbox("Просвет кишки", ["не изменен", "несколько сужен", "расширен"])
    colon_tonus = st.selectbox("Тонус кишки", ["нормальный", "повышен", "снижен"])
    colon_folds = st.selectbox("Циркулярные складки", ["обычных размеров", "высокие", "сглажены"])
    colon_color = st.selectbox("Цвет слизистой", ["розовый", "бледный", "красный / гиперемирована"])
    colon_surface = st.selectbox("Поверхность слизистой", ["гладкая, блестящая", "матовая", "неровная"])
    colon_vessels = st.selectbox("Сосудистый рисунок", ["четкий", "усилен", "ослаблен", "смазан / перестроен", "полностью отсутствует"])
    
    has_contents = st.checkbox("Наличие кишечного содержимого")
    contents_desc = ""
    if has_contents:
        c_loc = st.selectbox("Локализация содержимого", ["в куполе слепой кишки", "в правых отделах", "в сигмовидной и прямой кишке", "по всем отделам"])
        c_amount = st.selectbox("Количество", ["незначительное", "умеренное", "выраженное"])
        c_type = st.selectbox("Характер", ["жидкое", "оформленное", "смешанного характера"])
        c_hampers = st.radio("Влияние на осмотр", ["не затрудняет осмотр", "затрудняет детальный осмотр слизистой"])
        contents_desc = f"В {c_loc} определяется {c_amount} количество {c_type} кишечного содержимого, {c_hampers}."

with col_right:
    # ---------------------------------------------------------
    # 4. Модуль Язвенного Колита (ЯК)
    # ---------------------------------------------------------
    st.header("4. Модуль активности Язвенного Колита (ЯК)")
    eval_uc = st.checkbox("Оценивать признаки воспалительных заболеваний (ЯК)", value=False)
    
    uc_summary = "Признаков воспалительных заболеваний кишечника (ЯК) не выявлено."
    
    if eval_uc:
        montreal = st.radio(
            "Монреальская классификация (протяженность)",
            [
                "E1 — Проктит (воспаление ограничено прямой кишкой, до 15 см от ануса)",
                "E2 — Левосторонний колит (поражение ограничено дистальнее селезеночного изгиба)",
                "E3 — Тотальный колит / панколит (поражение проксимальнее селезеночного изгиба)",
                "Ремиссия / Норма (воспалительных изменений не выявлено)"
            ]
        )
        demarcation = st.text_input("Линия демаркации (ориентир, см от ануса)", value="не выражена / четкая на 15 см")
        
        mayo_score = st.slider("Индекс активности Mayo (MES, 0-3)", 0, 3, 1, 
                              help="0 - Норма; 1 - Легкая; 2 - Умеренная; 3 - Тяжелая")
        
        st.subheader("Калькулятор UCEIS (Ulcerative Colitis Endoscopic Index of Severity)")
        u_col1, u_col2, u_col3 = st.columns(3)
        with u_col1:
            uceis_v = st.selectbox("Сосуды (0-2)", [0, 1, 2], format_func=lambda x: f"{x} - {['Норма', 'Частично стерт', 'Отсутствует'][x]}")
        with u_col2:
            uceis_b = st.selectbox("Кровотечение (0-3)", [0, 1, 2, 3], format_func=lambda x: f"{x} - {['Нет', 'Пятнистое/контактное', 'Люминальное', 'Массивное/сгустки'][x]}")
        with u_col3:
            uceis_u = st.selectbox("Язвы (0-3)", [0, 1, 2, 3], format_func=lambda x: f"{x} - {['Нет', 'Эрозии ≤5мм', 'Поверхностные >5мм', 'Глубокие кратерообразные'][x]}")
        
        uceis_total = uceis_v + uceis_b + uceis_u
        st.markdown(f"**Суммарный UCEIS:** **{uceis_total} / 8** (Сосуды: {uceis_v}, Кровь: {uceis_b}, Язвы: {uceis_u})")
        
        pseudopolyps = st.selectbox("Псевдополипы", ["не обнаружены", "единичные воспалительные псевдополипы", "множественный псевдополипоз"])
        uc_biopsy = st.text_input("Биопсия при ЯК", value="взята биопсия из пораженных участков (2 флакона)")
        
        uc_summary = (
            f"Эндоскопическая картина язвенного колита, локализация: {montreal.split('—')[0].strip()}. "
            f"Линия демаркации: {demarcation}. "
            f"Индекс активности Mayo (MES): {mayo_score}. "
            f"Шкала UCEIS: {uceis_total}/8 (Сосудистый рисунок: {uceis_v}, Кровоточивость: {uceis_b}, Эрозии/Язвы: {uceis_u}). "
            f"Псевдополипы: {pseudopolyps}. Биопсия: {uc_biopsy}."
        )

    # ---------------------------------------------------------
    # 5. Описание полипов и опухолей (Париж + NICE)
    # ---------------------------------------------------------
    st.header("5. Описание полипов / образований (Париж и NICE)")
    has_polyp = st.checkbox("Выявлены полипы / образования", value=False)
    
    polyp_summary = "Эпителиальных образований и полипов не выявлено."
    
    if has_polyp:
        p_loc = st.selectbox("Локализация образования", [
            "в слепой кишке", "в восходящей ободочной кишке", "в печеночном изгибе", 
            "в поперечно-ободочной кишке", "в селезеночном изгибе", "в нисходящей ободочной кишке", 
            "в сигмовидной кишке", "в прямой кишке"
        ])
        p_size = st.number_input("Размер образования (мм)", min_value=1, max_value=150, value=6)
        
        p_paris = st.selectbox("Морфология по Парижской классификации", [
            "0-Ip (полиповидное на ножке)",
            "0-Isp (полиповидное на полуножке)",
            "0-Is (сидячее на широком основании)",
            "0-IIa (плоское приподнятое)",
            "0-IIb (плоское)",
            "0-IIc (плоское углубленное)",
            "0-III (изъязвленное)"
        ])
        
        st.subheader("Классификация NICE (NBI International Colorectal Endoscopic)")
        p_nice_type = st.radio("Тип по шкале NICE", [
            "NICE Type 1 (Гиперпластический / Неоплазия отсутствует)",
            "NICE Type 2 (Аденома / Доброкачественная неоплазия)",
            "NICE Type 3 (Инвазивный рак / Глубокая подслизистая инвазия)"
        ])
        
        p_action = st.selectbox("Выполненное вмешательство", [
            "Холодная петлевая полипэктомия (CSP)",
            "Горячая петлевая полипэктомия (HSP)",
            "Щипцовая поисковая биопсия",
            "Эндоскопическая резекция слизистой (EMR)",
            "Образование маркировано, направлен на эндохирургическое лечение (ESD / хирургию)"
        ])
        p_hist = st.radio("Фрагменты извлечены на гистологическое исследование?", ["Да", "Нет"], horizontal=True)
        
        polyp_summary = (
            f"Выявлено образование {p_loc}: размер {p_size} мм, тип по Парижской классификации {p_paris.split('(')[0].strip()}, "
            f"классификация {p_nice_type.split('(')[0].strip()}. "
            f"Выполнено: {p_action}. Извлечение материала на гистологическое исследование: {p_hist.lower()}."
        )

# ---------------------------------------------------------
# 6. Генерация итогового протокола
# ---------------------------------------------------------
st.divider()
st.header("📄 Сформированный протокол для МИС")

ti_text_formatted = f" **Подвздошная кишка:** {ti_status}." if ti_status != "не осмотрен" else ""

protocol_text = f"""ПРОТОКОЛ КОЛОНОСКОПИИ

Аппарат введен: {depth}.
Илеоцекальный клапан: {ic_form} формы, ориентирован {ic_orient}. Устье {ic_ostium}, {ic_ostium_shape} формы.{ti_text_formatted}

ПОДГОТОВКА КИШЕЧНИКА:
По Бостонской шкале (BBPS): Правый {bbps_r} + Поперечный {bbps_t} + Левый {bbps_l} = {bbps_total}/9 баллов ({prep_status_str}).

ОПИСАНИЕ ТОЛСТОЙ КИШКИ:
Просвет ободочной кишки {colon_lumen}, тонус {colon_tonus}, циркулярные складки {colon_folds}. Стенка кишки эластична. 
Слизистая оболочка {colon_color} цвета, с {colon_surface} поверхностью. Сосудистый рисунок {colon_vessels}.
{contents_desc}

ОБРАЗОВАНИЯ И ПОЛИПЫ:
{polyp_summary}

ОЦЕНКА ВОСПАЛЕНИЯ / ЯЗВЕННОГО КОЛИТА:
{uc_summary}

ЗАКЛЮЧЕНИЕ:
1. Качество подготовки по BBPS: {bbps_total}/9 баллов ({'адекватная' if is_adequate else 'неадекватная'}).
2. {uc_summary if eval_uc else 'Воспалительных изменений толстой кишки не выявлено.'}
3. {polyp_summary if has_polyp else 'Эпителиальных образований не выявлено.'}
"""

st.text_area("Готовый протокол (скопируйте в буфер обмена):", protocol_text, height=350)

st.download_button(
    label="💾 Скачать протокол в формате .txt",
    data=protocol_text,
    file_name="colonoscopy_protocol.txt",
    mime="text/plain"
)
